        playSoundEffect(0x162);
        break;
    case 11:
        playSoundEffect(0x163);
        break;
    case 12:
        playSoundEffect(0x15E);
        break;
    case 18:
        playSoundEffect(0x15C);
        break;
    case 14:
        playSoundEffect(0x15F);
        break;
    case 13:
    case 17:
        playSoundEffect(0x160);
        break;
    case 3:
        playSoundEffect(0x164);
        break;
    case 4:
        playSoundEffect(0x166);
        break;
